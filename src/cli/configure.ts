/**
 * The first-run configuration step: link this machine as a Signal device and
 * write the config.toml that the daemon needs, without a hand edit.
 *
 * The step's check is deliberately narrow — "config.toml exists and names an
 * account" — and the apply is the only part that needs a phone. The link is a
 * four-phase `DeviceLink` (start, QR, finish, stop) and the whole phase order
 * lives in `driveLink`, so a fake linker can prove the config bytes, the
 * no-overwrite rule and the daemon shutdown without Signal running.
 *
 * An existing config is the operator's work: this module never merges, edits or
 * rewrites one. It only fills the empty first run, and it does that with the
 * linked number `finishLink` returned — never a guess.
 */
import { oneLine } from "../oneLine.js";
import fs from "node:fs";
import path from "node:path";
import { installedCopies } from "./signalCliInstall.js";
import type { ConfigRead, Print, SetupStep, StepContext } from "./setup.js";

/** The data directory's default daemon endpoint; config.toml does not exist yet. */
export const LINK_HOST = "127.0.0.1";
export const LINK_PORT = 8080;

/** Roughly three minutes at three seconds a poll, as `npm run link` always did. */
export const LINK_ATTEMPTS = 60;
export const LINK_INTERVAL_MS = 3_000;

const LINK_FIX =
  'run "node dist/index.js setup" to install signal-cli (it needs Java 17 or newer) ' +
  "and link this device";

const CONFIG_FIX = 'run "node dist/index.js setup" to link this device and write config.toml';

/** The argv signal-cli runs with, and the launcher config.toml names. */
export interface SignalCommand {
  cliPath: string;
  command: string[];
}

/** What a first-run config needs: the linked number, the project and the tool. */
export interface InitialConfigInput {
  /** The data directory that will hold config.toml. */
  dir: string;
  /** The number `finishLink` returned. */
  account: string;
  /** The one project a new config names: the directory setup ran in. */
  projectPath: string;
  signal: SignalCommand;
}

export interface InitialConfigResult {
  path: string;
  /** False when a config already existed and was left byte-identical. */
  written: boolean;
}

/**
 * A TOML literal string for a path or argv element, so Windows backslashes are
 * not escape sequences. A value a literal string cannot carry falls back to a
 * basic string, which TOML and JSON escape the same way for these characters.
 */
function literal(value: string): string {
  return value.includes("'") || /[\r\n]/.test(value)
    ? JSON.stringify(value)
    : `'${value}'`;
}

function basic(value: string): string {
  return JSON.stringify(value);
}

/** The project name the operator will see in Signal: the directory's leaf. */
export function projectName(projectPath: string): string {
  const resolved = path.resolve(projectPath);
  return path.basename(resolved) || "project";
}

/**
 * The config template. It names the linked account, the installed signal-cli,
 * the plugin agent and one project; every other table takes its schema default.
 * The comment says out loud what the step guarantees: this file is never
 * rewritten once it exists.
 */
export function renderInitialConfig(input: InitialConfigInput): string {
  const { signal } = input;
  const name = projectName(input.projectPath);
  return [
    "# Generated by the SignalConnector setup step.",
    "# An existing config.toml is never rewritten; edit this file freely.",
    "",
    "[channel]",
    'kind = "note-to-self"',
    "",
    "[signal]",
    `cliPath = ${literal(signal.cliPath)}`,
    `command = [${signal.command.map(literal).join(", ")}]`,
    `account = ${basic(input.account)}`,
    "manageDaemon = true",
    `daemonHost = ${basic(LINK_HOST)}`,
    `daemonPort = ${LINK_PORT}`,
    "",
    "[agent]",
    'kind = "plugin"',
    'serverUrl = "http://127.0.0.1:4096"',
    'opencodePath = "opencode"',
    "",
    "[[projects]]",
    `name = ${basic(name)}`,
    `path = ${literal(input.projectPath)}`,
    "",
  ].join("\n");
}

/**
 * Writes config.toml only when it is absent. `wx` is the no-overwrite
 * guarantee, the file is created user-only, and a failed write removes the
 * file it started so a bad data directory leaves no partial config.
 */
export function writeInitialConfig(input: InitialConfigInput): InitialConfigResult {
  if (input.account.trim().length === 0) {
    throw new Error("refusing to write config.toml without a linked account");
  }
  if (input.projectPath.trim().length === 0) {
    throw new Error("refusing to write config.toml without a project path");
  }

  const file = path.join(input.dir, "config.toml");
  let existing: fs.Stats | undefined;
  try {
    existing = fs.statSync(file);
  } catch (err: unknown) {
    if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
  }
  if (existing) {
    if (!existing.isFile()) {
      throw new Error(`${file} exists but is not a file`);
    }
    return { path: file, written: false };
  }

  fs.mkdirSync(input.dir, { recursive: true, mode: 0o700 });
  try {
    fs.writeFileSync(file, renderInitialConfig(input), {
      encoding: "utf8",
      flag: "wx",
      mode: 0o600,
    });
  } catch (err: unknown) {
    if ((err as NodeJS.ErrnoException).code === "EEXIST") {
      return { path: file, written: false };
    }
    // Only a file this call started can be partial; EEXIST was handled above.
    try {
      fs.rmSync(file, { force: true });
    } catch {
      // keep the write's reason, not a cleanup error
    }
    throw err;
  }
  return { path: file, written: true };
}

/**
 * The four live phases, injectable as one object: a test fakes this, the
 * production implementation lives in `link.ts`. `finish` returns "" while the
 * QR has not been scanned and throws only when the link is refused.
 */
export interface DeviceLink {
  /** Starts the daemon and asks it for a device-link URI. */
  start(): Promise<string>;
  /** Renders `uri` as an image and returns the image's path. */
  qr(uri: string): Promise<string>;
  /** One poll of the link; the number when linked, "" while waiting. */
  finish(uri: string): Promise<string>;
  /** Stops the daemon; called on every path. */
  stop(): Promise<void>;
}

export interface DriveLinkOptions {
  print: Print;
  /** Opens the QR image; the script does this, the setup step only prints it. */
  open?: (qrPath: string) => void;
  attempts?: number;
  intervalMs?: number;
}

export interface LinkProgress {
  uri: string;
  qrPath: string;
  /** The number the device linked as. */
  number: string;
}

const delay = (ms: number): Promise<void> => new Promise((resolve) => setTimeout(resolve, ms));

/**
 * The one phase order both callers share: start, render the QR, poll until the
 * operator scans it, and stop the daemon in a `finally` on every path. The URI
 * is printed as well as rendered, so a terminal-only machine can still link.
 */
export async function driveLink(
  link: DeviceLink,
  options: DriveLinkOptions,
): Promise<LinkProgress> {
  const attempts = options.attempts ?? LINK_ATTEMPTS;
  const intervalMs = options.intervalMs ?? LINK_INTERVAL_MS;

  try {
    const uri = await link.start();
    const qrPath = await link.qr(uri);

    options.print("Link this device to your Signal account:");
    options.print("1. In Signal: Settings -> Linked Devices -> Link New Device.");
    options.print("2. Scan the QR image, or generate one from the URI.");
    options.print(uri);
    options.print(`QR image: ${qrPath}`);
    if (options.open) {
      options.print("Opening the QR image — scan it with Signal.");
      options.open(qrPath);
    } else {
      options.print("Waiting for the QR to be scanned...");
    }

    for (let i = 0; i < attempts; i++) {
      // A rejection here is a refusal, not a slow scan: stop and report it.
      const number = await link.finish(uri);
      if (number.length > 0) return { uri, qrPath, number };
      if (i + 1 < attempts) await delay(intervalMs);
    }
    throw new Error('Link timed out; run "node dist/index.js setup" (or "npm run link") again to retry.');
  } finally {
    try {
      await link.stop();
    } catch {
      // stopping is best effort; the link result or its reason is what matters
    }
  }
}

/** The config choices a new file records. */
export interface LinkDeviceConfig {
  signal: SignalCommand;
  /** The project a new config names: the directory setup ran in. */
  projectPath: string;
}

export interface LinkDeviceOptions {
  dataDir: string;
  config: LinkDeviceConfig;
  link: DeviceLink;
  print: Print;
  open?: (qrPath: string) => void;
  attempts?: number;
  intervalMs?: number;
}

export interface LinkOutcome {
  account: string;
  configPath: string;
  /** False when a config appeared while linking and was left untouched. */
  written: boolean;
  projectPath: string;
}

/**
 * Link the device, then fill the empty first run. A config that appears while
 * the QR waits is reported rather than replaced, and the linked number is the
 * one the daemon returned.
 */
export async function linkDevice(options: LinkDeviceOptions): Promise<LinkOutcome> {
  const progress = await driveLink(options.link, {
    print: options.print,
    ...(options.open ? { open: options.open } : {}),
    ...(options.attempts !== undefined ? { attempts: options.attempts } : {}),
    ...(options.intervalMs !== undefined ? { intervalMs: options.intervalMs } : {}),
  });

  const result = writeInitialConfig({
    dir: options.dataDir,
    account: progress.number,
    projectPath: options.config.projectPath,
    signal: options.config.signal,
  });

  if (result.written) {
    options.print(
      `Linked as ${progress.number}; wrote ${result.path} with project ` +
        `${projectName(options.config.projectPath)} (${options.config.projectPath}).`,
    );
  } else {
    options.print(
      `Linked as ${progress.number}; ${result.path} already exists and was left untouched.`,
    );
  }
  return {
    account: progress.number,
    configPath: result.path,
    written: result.written,
    projectPath: options.config.projectPath,
  };
}

/** True when `executable` (plus a Windows launcher extension) is on PATH. */
function commandOnPath(executable: string): boolean {
  const pathValue = process.env.PATH ?? "";
  const extensions =
    process.platform === "win32"
      ? (process.env.PATHEXT ?? ".EXE;.CMD;.BAT;.COM").split(";").filter(Boolean)
      : [""];
  for (const dir of pathValue.split(path.delimiter)) {
    if (dir.length === 0) continue;
    for (const extension of extensions) {
      const candidate = path.join(dir, `${executable}${extension}`);
      // existsSync is case-insensitive on Windows, so signal-cli.BAT matches.
      if (fs.existsSync(candidate)) return true;
    }
    if (fs.existsSync(path.join(dir, executable))) return true;
  }
  return false;
}

/** Config.toml and the daemon want this form of the tool on this platform. */
export function signalCommandFor(
  dataDir: string,
  platform: NodeJS.Platform = process.platform,
): SignalCommand {
  const copy = installedCopies(dataDir, platform)[0];
  if (!copy) return { cliPath: "signal-cli", command: ["signal-cli"] };

  if (platform === "win32") {
    // The release's .bat overflows cmd's line limit on deep install paths, so
    // the generated config names java with the wildcard classpath instead.
    const java = process.env.JAVA_HOME
      ? path.join(process.env.JAVA_HOME, "bin", "java.exe")
      : "java";
    return {
      cliPath: copy.path,
      command: [
        java,
        "--enable-native-access=ALL-UNNAMED",
        "-cp",
        path.join(copy.home, "lib", "*"),
        "org.asamk.signal.Main",
      ],
    };
  }
  return { cliPath: copy.path, command: [copy.path] };
}

/** A linker is injectable so the suite never needs a phone or signal-cli. */
export type LinkerFactory = (options: {
  dataDir: string;
  signal: SignalCommand;
  projectPath: string;
}) => DeviceLink;

/** Read the current file, not the context snapshot taken before the run. */
async function currentConfig(dir: string): Promise<ConfigRead> {
  // Dynamic so doctor's static graph stays free of config, toml and zod.
  const { readConfig } = await import("../config/config.js");
  return readConfig(dir);
}

/**
 * The setup step. Its check completes an empty first run and refuses to touch
 * anything else; its apply links the device, writes a new config, and reports
 * the number and project it wrote.
 */
export function linkStep(linker?: LinkerFactory): SetupStep {
  return {
    id: "device-link",
    title: "Signal device link",
    check: async (ctx) => {
      const read = await currentConfig(ctx.dataDir);
      if (read.ok) {
        const account = read.config.signal.account?.trim() ?? "";
        if (account.length > 0) {
          return {
            status: "ok",
            reason: `config.toml names the linked account ${account}`,
          };
        }
        const line = 'account = "+<your number>"';
        return {
          status: "failed",
          reason: `config.toml has no signal.account; add this line under [signal]: ${line}`,
          fix: `edit ${path.join(ctx.dataDir, "config.toml")} — setup never rewrites an existing config`,
        };
      }

      if (read.absent) {
        const signalCli =
          installedCopies(ctx.dataDir)[0] !== undefined || commandOnPath("signal-cli");
        return signalCli
          ? {
              status: "missing",
              reason: `config.toml does not exist in ${ctx.dataDir}`,
              fix: CONFIG_FIX,
            }
          : {
              status: "missing",
              reason: `config.toml does not exist and signal-cli is not installed under ` +
                `${path.join(ctx.dataDir, "signal-cli")} or on PATH`,
              fix: LINK_FIX,
            };
      }

      return {
        status: "failed",
        reason: oneLine(read.reason),
        fix: `fix ${path.join(ctx.dataDir, "config.toml")} and run setup again`,
      };
    },
    apply: async (ctx: StepContext) => {
      const signal = signalCommandFor(ctx.dataDir);
      const projectPath = process.cwd();
      // Dynamic so doctor, which only checks, never loads daemon or config code.
      const factory = linker ?? (await import("./link.js")).signalLinker;
      const link = factory({ dataDir: ctx.dataDir, signal, projectPath });
      await linkDevice({
        dataDir: ctx.dataDir,
        config: { signal, projectPath },
        link,
        print: ctx.print,
      });
    },
  };
}
