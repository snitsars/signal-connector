#Requires -Version 5.1
<#
.SYNOPSIS
  One-shot host setup for SignalConnector on Windows:
  ensure Java 25, install signal-cli, write config.toml, and print next steps.

.EXAMPLE
  pwsh scripts/setup.ps1
  pwsh scripts/setup.ps1 -ProjectName myapp -ProjectPath C:\Sources\myapp
  pwsh scripts/setup.ps1 -SkipJava
#>
[CmdletBinding()]
param(
    [switch]$SkipJava,
    [string]$ProjectName = (Split-Path -Leaf (Get-Location).Path),
    [string]$ProjectPath = (Get-Location).Path,
    [string]$OpenCodeServerUrl = 'http://127.0.0.1:4096',
    [int]$DaemonPort = 8080
)

$ErrorActionPreference = 'Stop'
Write-Host "SignalConnector setup" -ForegroundColor Cyan
Write-Host ""

# 1. Java
if ($SkipJava) {
    Write-Host "Skipping Java check (-SkipJava)."
} else {
    & (Join-Path $PSScriptRoot 'ensure-java.ps1')
}

# 2. signal-cli
$signalCli = (& (Join-Path $PSScriptRoot 'install-signal-cli.ps1') | Select-Object -Last 1)
if (-not (Test-Path $signalCli)) { throw "signal-cli install did not return a path." }

# 3. config.toml
$cfgDir = Join-Path $env:APPDATA 'SignalConnector'
New-Item -ItemType Directory -Force -Path $cfgDir | Out-Null
$cfgPath = Join-Path $cfgDir 'config.toml'

if (Test-Path $cfgPath) {
    Write-Host "Config already exists (left untouched): $cfgPath" -ForegroundColor Yellow
} else {
    $toml = @"
# Generated by scripts/setup.ps1. Paths are TOML literal strings.

[channel]
kind = "note-to-self"

[signal]
cliPath = '$signalCli'
account = ""
manageDaemon = true
daemonHost = "127.0.0.1"
daemonPort = $DaemonPort

[agent]
kind = "opencode-server"
serverUrl = "$OpenCodeServerUrl"
opencodePath = "opencode"

[outbound]
minIntervalMs = 1500
maxPerMinute = 20

[[projects]]
name = "$ProjectName"
path = '$ProjectPath'
"@
    Set-Content -Path $cfgPath -Value $toml -Encoding utf8
    Write-Host "Wrote config: $cfgPath" -ForegroundColor Green
}

Write-Host ""
Write-Host "Next steps" -ForegroundColor Cyan
Write-Host "  1. Install deps + start opencode server:"
Write-Host "       npm install"
Write-Host "       pwsh scripts/start-opencode.ps1"
Write-Host "  2. Link your Signal device (scan the QR):"
Write-Host "       pwsh scripts/link-device.ps1"
Write-Host "  3. Put the linked number into signal.account:"
Write-Host "       $cfgPath"
Write-Host "  4. Run the daemon:"
Write-Host "       pwsh scripts/run.ps1"
